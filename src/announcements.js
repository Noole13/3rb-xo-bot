import { SlashCommandBuilder, PermissionFlagsBits, MessageFlags, EmbedBuilder } from "discord.js";

// تعريف أمر السلاش
export const announcementCommand = new SlashCommandBuilder()
  .setName("إعلان-التحديثات")
  .setDescription("إرسال رسالة تحديثات ألعاب البوت الرسمية في القناة الحالية")
  .setDefaultMemberPermissions(PermissionFlagsBits.ManageChannels);

// دالة تنفيذ الأمر
export async function executeAnnouncement(interaction) {
  // إنشاء الـ Embed المرتب والمنظم بعناية
  const updateEmbed = new EmbedBuilder()
    .setColor(0xF1C40F)
    .setTitle("🎉 تحديث جديد ومثير في سيرفرنا!")
    .setDescription("تم الانتهاء بحمد الله من بناء وتطوير نظام ألعاب البوت بالكامل! 🎮✨\n\nلقد قمنا بإطلاق قائمة ممتعة ومتنوعة من الألعاب لتستمتعوا بها معنا. إليكم الألعاب وشرح طريقة اللعب:")
    .addFields(
      { 
        name: "🪑 لعبة الكراسي الموسيقية", 
        value: "لعبة جماعية ممتعة تتطلب السرعة للبقاء على الكراسي حتى الوصول للفوز وتسجيل نقطة في لوحة الشرف.\n🔹 **طريقة اللعب:** تفاعل مع الرسالة أو انقر على الزر المخصص عند بدء الجولة لتأمين مقعدك!" 
      },
      { name: "\u200B", value: "\u200B" }, // مسافة فاصلة مرتبة
      { 
        name: "🏴 لعبة الأعلام (!اعلام أو !flags)", 
        value: "اختبار ذكاء ومعرفة بأسماء أعلام الدول المختلفة.\n🔹 **طريقة اللعب:** اكتب الأمر `!اعلام` أو `!flags` في القناة وقم بكتابة اسم الدولة الصحيح عند ظهور علمها." 
      },
      { name: "\u200B", value: "\u200B" },
      { 
        name: "🌍 لعبة العواصم (!عواصم)", 
        value: "تحدٍ ثقافي لمعرفة عواصم دول العالم بسرعة البديهة.\n🔹 **طريقة اللعب:** اكتب الأمر `!عواصم` في القناة وأجب باسم عاصمة الدولة المطلوبة بأسرع وقت." 
      },
      { name: "\u200B", value: "\u200B" },
      { 
        name: "🧠 لعبة الأسئلة العامة (!سؤال)", 
        value: "أسئلة منوعة لاختبار معلوماتك العامة وسرعة إجابتك.\n🔹 **طريقة اللعب:** اكتب الأمر `!سؤال` وكن أول من يجيب على السؤال المعروض." 
      },
      { name: "\u200B", value: "\u200B" },
      { 
        name: "❌ ⭕ لعبة XO الكلاسيكية (/xo)", 
        value: "التحدي الشهير، حيث يمكنك اللعب ضد أصدقائك أو ضد الذكاء الاصطناعي (البوت).\n🔹 **طريقة اللعب:** استخدم أمر `/xo` وحدد المنافس (صديقك أو البوت) وابدأ التحدي." 
      },
      { name: "\u200B", value: "\u200B" },
      { 
        name: "📊 لوحة الشرف ونظام النقاط (/top)", 
        value: "نظام متكامل لحفظ انتصاراتكم وعرض أفضل اللاعبين في السيرفر.\n🔹 **طريقة الاستخدام:** اكتب أمر `/top` لعرض قائمة المتصدرين وترتيب اللاعبين." 
      },
      { name: "\u200B", value: "\u200B" },
      { 
        name: "⚠️ تنبيه هام", 
        value: "يرجى دائماً استخدام هذه الألعاب داخل قناة الألعاب المخصصة في السيرفر للحفاظ على تنظيم السيرفر!" 
      }
    )
    .setFooter({ text: "جهّزوا أنفسكم، ونتمنى للجميع أوقاتاً مليئة بالحماس والتحدي! 🚀🔥" });

  // إرسال الـ Embed في القناة التي كُتب فيها الأمر
  await interaction.channel.send({ embeds: [updateEmbed] });

  // رد مخفي للمشرف يؤكد نجاح الإرسال
  await interaction.reply({
    content: "✅ تم إرسال رسالة إعلان التحديثات بنجاح في هذه القناة!",
    flags: MessageFlags.Ephemeral,
  });
}
