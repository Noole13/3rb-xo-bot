import { SlashCommandBuilder, PermissionFlagsBits, MessageFlags } from "discord.js";

// تعريف أمر السلاش
export const announcementCommand = new SlashCommandBuilder()
  .setName("إعلان-التحديثات")
  .setDescription("إرسال رسالة تحديثات ألعاب البوت الرسمية في القناة الحالية")
  .setDefaultMemberPermissions(PermissionFlagsBits.ManageChannels);

// دالة تنفيذ الأمر
export async function executeAnnouncement(interaction) {
  const updateMessage = `🎉 **تحديث جديد ومثير في سيرفرنا!** تم الانتهاء بحمد الله من بناء وتطوير نظام ألعاب البوت بالكامل! 🎮✨

لقد قمنا بإطلاق قائمة ممتعة ومتنوعة من الألعاب لتستمتعوا بها معنا. إليكم الألعاب التي أضفناها:

* 🪑 **لعبة الكراسي الموسيقية:** لعبة جماعية ممتعة تتطلب السرعة للبقاء على الكراسي حتى الوصول للفوز وتسجيل نقطة في لوحة الشرف.

* 🏴 **لعبة الأعلام (!اعلام أو !flags):** اختبار ذكاء ومعرفة بأسماء أعلام الدول المختلفة.

* 🌍 **لعبة العواصم (!عواصم):** تحدٍ ثقافي لمعرفة عواصم دول العالم بسرعة البديهة.

* 🧠 **لعبة الأسئلة العامة (!سؤال):** أسئلة منوعة لاختبار معلوماتك العامة وسرعة إجابتك.

* ❌ ⭕ **لعبة XO الكلاسيكية (/xo):** التحدي الشهير، حيث يمكنك اللعب ضد أصدقائك أو ضد الذكاء الاصطناعي (البوت).

* 📊 **لوحة الشرف ونظام النقاط (/top):** نظام متكامل لحفظ انتصاراتكم وعرض أفضل اللاعبين في السيرفر.

> ⚠️ **تنبيه:** يرجى دائماً استخدام هذه الألعاب داخل قناة الألعاب المخصصة في السيرفر!

جهّزوا أنفسكم، ونتمنى للجميع أوقاتاً مليئة بالحماس والتحدي! 🚀🔥`;

  // إرسال الرسالة في القناة التي كُتب فيها الأمر
  await interaction.channel.send(updateMessage);

  // رد مخفي للمشرف يؤكد نجاح الإرسال
  await interaction.reply({
    content: "✅ تم إرسال رسالة إعلان التحديثات بنجاح في هذه القناة!",
    flags: MessageFlags.Ephemeral,
  });
}
